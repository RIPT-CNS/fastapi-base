"""Every fixed option of the project. All are StrEnum: members compare equal to their string
values (RouteGroup.READ == "read"), so they also work where plain strings are accepted."""

from enum import StrEnum


class Environment(StrEnum):
    DEV = "dev"  # hot reload
    TEST = "test"
    STAGING = "staging"
    PROD = "prod"  # workers + strict config checks


# ------------------------------------------------------------------ users / auth
class UserRole(StrEnum):
    """Role names. Keep them identical to Keycloak realm/client role names."""

    ADMIN = "admin"
    USER = "user"
    GUEST = "guest"


class UserGender(StrEnum):
    MALE = "male"
    FEMALE = "female"
    OTHER = "other"


class AuthProvider(StrEnum):
    LOCAL = "local"
    KEYCLOAK = "keycloak"


# ------------------------------------------------------------------------ BaseAPI
class Route(StrEnum):
    """Keys of the routes generated by BaseAPI (disabled_routes, route_config).
    Never equal to a RouteGroup value, so a key never shadows a group."""

    COUNT = "count"
    GET_FIRST = "get_first"
    GET_LIST = "get_list"
    GET_MANY = "get_many"
    GET_PAGE = "get_page"
    GET_ONE = "get_one"
    CREATE_ONE = "create_one"
    CREATE_MANY = "create_many"
    UPDATE_ONE = "update_one"
    PATCH_ONE = "patch_one"
    UPDATE_MANY = "update_many"
    PATCH_MANY = "patch_many"
    UPDATE_ALL = "update_all"
    PATCH_ALL = "patch_all"
    DELETE_ONE = "delete_one"
    DELETE_MANY = "delete_many"
    DELETE_ALL = "delete_all"
    IMPORT_TEMPLATE = "import_template"
    IMPORT_VALIDATE = "import_validate"
    IMPORT_DATA = "import_data"
    EXPORT_DATA = "export_data"
    EXPORT_IMPORTABLE = "export_importable"


class RouteGroup(StrEnum):
    """Route groups: also the action part of permissions ("<permission_prefix>:<group>")."""

    READ = "read"
    CREATE = "create"
    UPDATE = "update"
    DELETE = "delete"
    IMPORT = "import"
    EXPORT = "export"


class QueryParam(StrEnum):
    """Query params with a fixed meaning: never read as shorthand filters (?field__op=value)."""

    FILTERS = "filters"
    SEARCH = "search"
    SEARCH_FIELDS = "search_fields"
    SORT = "sort"
    PAGE = "page"
    PAGE_SIZE = "page_size"
    IDS = "ids"
    FIELDS = "fields"
    CONFIRM = "confirm"
    MODE = "mode"
    FORMAT = "format"


class ExportFormat(StrEnum):
    XLSX = "xlsx"  # built on disk, then streamed
    CSV = "csv"  # streamed while rows are read


class ImportMode(StrEnum):
    INSERT = "insert"  # every row is a new record
    UPDATE = "update"  # every row must match an existing record by the import key
    UPSERT = "upsert"  # update when the key matches, insert otherwise


# -------------------------------------------------------------- dynamic filters
class FilterOperator(StrEnum):
    EQ = "eq"
    NE = "ne"
    GT = "gt"
    GTE = "gte"
    LT = "lt"
    LTE = "lte"
    IN = "in"
    NOT_IN = "not_in"
    BETWEEN = "between"
    LIKE = "like"  # contains, case insensitive
    NOT_LIKE = "not_like"
    STARTSWITH = "startswith"
    ENDSWITH = "endswith"
    ISNULL = "isnull"


class LogicalOperator(StrEnum):
    AND = "and"
    OR = "or"
    NOT = "not"
